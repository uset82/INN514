"""Export the INN514 companion as a plain-text knowledge pack for Grok Principal.

    C:/Python313/python.exe workspace/lecture-audio/scripts/export_knowledge.py <out_dir>

Writes <out_dir>/INDEX.md, classes/class-<n>.md and papers/paper-<nn>.md from the same data the
site shows (site/data/<id>.json, the build_site catalog and reading_lib's paper facts), so the
pack never says more or less than the published companion. Only reviewed papers
(site/reviewed.json) are exported. Re-run after any change to a lecture or a reading, then
commit the pack in grok-watch-hub. It writes and overwrites its own files and deletes nothing;
any other file found in <out_dir> is listed so a person can decide what to do with it.
"""
import datetime
import json
import pathlib
import re
import sys

from build_site import CATALOG, SESSIONS
from reading_lib import ORDER, paper_meta

ROOT = pathlib.Path(__file__).resolve().parents[1]
DATA = ROOT / "site" / "data"
SITE_URL = "https://claude.ai/artifact/Nc3TALuXYR3W49sUshNs93"
STAMP = ("<!-- Generated by workspace/lecture-audio/scripts/export_knowledge.py in D:/HVL2025/514 on {date}. "
         "Do not edit here: change the companion and export again. -->")


def load(i):
    return json.loads((DATA / f"{i}.json").read_text(encoding="utf-8"))


def end(s):
    """Close a sentence without doubling its punctuation ("Progress or crisis?" stays as it is)."""
    return s if s.endswith((".", "?", "!")) else s + "."


def class_name(num):
    return "Bonus class" if num == "Bonus" else f"Class {num}"


def class_file(num):
    return f"classes/class-{'bonus' if num == 'Bonus' else num}.md"


def paper_file(pid):
    return f"papers/paper-{pid[1:]}.md"


def slide_text(sl):
    if not sl:
        return ""
    runs, a, b = [], sl[0], sl[0]
    for x in sl[1:]:
        if x == b + 1:
            b = x
        else:
            runs.append((a, b))
            a = b = x
    runs.append((a, b))
    return ("Slides " if len(sl) > 1 else "Slide ") + ", ".join(str(x) if x == y else f"{x}–{y}" for x, y in runs)


def checks_md(checks):
    if not checks:
        return []
    out = ["Check yourself:"]
    for c in checks:
        out += [f"- Q: {c['q']}", f"  A: {c['a']}"]
    return out + [""]


def page_span(lec):
    nums = [int(m) for c in lec["chapters"] for l in c.get("labels", []) for m in re.findall(r"\d+", l or "")]
    return f"{min(nums)}–{max(nums)}" if nums else ""


def main(out):
    sys.stdout.reconfigure(encoding="utf-8")
    today = datetime.date.today().isoformat()
    stamp = STAMP.format(date=today)
    reviewed = set(json.loads((ROOT / "site" / "reviewed.json").read_text(encoding="utf-8")))
    papers = [paper_meta(p) | {"id": p} for p in ORDER if p in reviewed and (DATA / f"{p}.json").exists()]
    num_of = {i: n for i, n, *_ in CATALOG}
    written = []

    def write(rel, lines):
        p = out / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
        written.append(rel)

    # One file per class
    class_rows = []
    for i, num, title, when, teacher, note in CATALOG:
        lec = load(i)
        mine = [m for m in papers if i in m["lectures"]]
        head = [stamp, f"# {class_name(num)}: {title}", "",
                f"Teacher: {teacher}. {when}. Summarised in English from the teacher's H2025 slides and the papers.",
                *( [note] if note else [] ),
                "Papers for this class: " + ("; ".join(f"Paper {m['num']} ({m['cite']}), {paper_file(m['id'])}" for m in mine) or "none") + ".",
                ""]
        body = []
        for ch in lec["chapters"]:
            src = slide_text(ch.get("slides", []))
            reads = ch.get("readings", "")
            meta = ". ".join(x for x in [src, f"Readings: {reads}" if reads and not reads.lower().startswith("none") else ""] if x)
            body += [f"## Chapter {ch['n']}. {ch['title']}", *( [end(meta)] if meta else [] ), ""]
            body += [p + "\n" for p in ch["paragraphs"]]
            body += checks_md(ch.get("checks", []))
        write(class_file(num), head + body)
        class_rows.append((num, title, teacher, when, note, lec, mine))

    # One file per paper
    paper_rows = []
    for m in papers:
        lec = load(m["id"])
        classes = [class_name(num_of[l]) for l in m["lectures"] if l in num_of]
        head = [stamp, f"# Paper {m['num']}: {m['title']}", "",
                f"{m['authors']} ({m['year']}). {m['source']}.",
                f"Read with: {', '.join(classes)}. Pages {page_span(lec)}.", ""]
        if m["id"] == "P02":
            head += ["Note: this is a conference paper marked \"paper in preparation, do not quote\". Paraphrase it; never quote it. "
                     "It has no printed page numbers, so its page numbers are PDF pages.", ""]
        body = []
        for ch in lec["chapters"]:
            pages = ch.get("pages", "")
            body += [f"## Chapter {ch['n']}. {ch['title']}" + (f" ({'whole paper' if pages == 'the whole paper' else 'pages ' + pages})" if pages else ""), ""]
            for k, p in enumerate(ch["paragraphs"]):
                label = (ch.get("labels") or [""] * len(ch["paragraphs"]))[k]
                if label:
                    body.append(f"### {label}")
                body += [p, ""]
            body += checks_md(ch.get("checks", []))
        write(paper_file(m["id"]), head + body)
        paper_rows.append((m, classes, lec))

    # The index Grok Principal reads first
    idx = [stamp, "# INN514 knowledge pack: index", "",
           "INN514, \"Innovation systems and sustainable transformation\", autumn 2026. This pack is the full text of the "
           "INN514 Course Companion, an unofficial study aid prepared with AI help and checked against the slides and "
           f"papers; the lecturers have not reviewed it. The companion itself: {SITE_URL}", "",
           "## How to answer an INN514 question", "",
           "1. Read this index, then open only the class or paper files the question needs.",
           "2. Answer only from these files. If they do not cover the question, say so plainly; do not fill the gap from memory.",
           "3. Say where the answer comes from: \"Class 4, chapter 3\" or \"Paper 14, page 764\".",
           "4. Speak it: a short spoken summary in Spanish, 3 to 5 sentences, unless the user asks for more. Keep course terms "
           "in English when Spanish would blur them (for example \"upward causation\").",
           "5. Class text is the companion's summary of the teacher's slides, not the teacher's own words; paper text is a "
           "summary of the paper, page by page. Never present either as a quotation.",
           "6. Paper 2 is marked \"paper in preparation, do not quote\": paraphrase it only.", "",
           "## Finding things", "",
           "- \"Class N\" or \"lecture N\" means the Kursplan session number: classes 1 to 6, then 9; the bonus class is separate. "
           "Sessions 7 and 8 have no slides of their own: they go through the papers.",
           "- \"Paper N\" is the number in the PDF file name (1 to 17), as on the site.",
           "- \"Page N\": find the paper whose pages include N in the table below. Several papers start at page 1, so use the "
           "author or the class to tell them apart.",
           "- \"Chapter N\" belongs to a class or a paper: each file lists its chapters in order.", "",
           "## Classes", ""]
    for num, title, teacher, when, note, lec, mine in class_rows:
        idx.append(f"### {class_name(num)}: {title}")
        idx.append(f"File: `{class_file(num)}`. Teacher: {teacher}. {when}." + (f" {note}" if note else ""))
        idx.append("Papers: " + (", ".join(f"Paper {m['num']} ({m['cite']})" for m in mine) or "none") + ".")
        idx.append(end("Chapters: " + "; ".join(f"{c['n']}. {c['title']}" for c in lec["chapters"])))
        idx.append("")
    idx.append("Sessions without slides: " + "; ".join(
        f"session {s['num']} ({s['when'].split(', ')[1]}), {s['title']}, {s['teacher']}" for s in SESSIONS) + ".")
    idx += ["", "## Papers", ""]
    for m, classes, lec in paper_rows:
        idx.append(f"### Paper {m['num']}: {m['title']}")
        idx.append(f"File: `{paper_file(m['id'])}`. {m['cite']}. {m['source']}. Pages {page_span(lec)}. Read with {', '.join(classes)}.")
        idx.append("Chapters: " + "; ".join(
            f"{c['n']}. {c['title']} ({'whole paper' if c.get('pages') == 'the whole paper' else 'pages ' + c.get('pages', '')})"
            for c in lec["chapters"]) + ".")
        idx.append("")
    write("INDEX.md", idx)

    words = sum(len((out / f).read_text(encoding="utf-8").split()) for f in written)
    print(f"wrote {len(written)} files to {out} ({words} words): 1 index, {len(class_rows)} classes, {len(paper_rows)} papers")
    others = sorted(str(p.relative_to(out)).replace("\\", "/") for p in out.rglob("*") if p.is_file()
                    and str(p.relative_to(out)).replace("\\", "/") not in written)
    if others:
        print("other files in the folder (left alone): " + ", ".join(others))
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    sys.exit(main(pathlib.Path(sys.argv[1])))
