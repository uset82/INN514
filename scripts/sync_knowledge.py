"""One-command sync of the INN514 knowledge pack into the watch hub.

    C:/Python313/python.exe workspace/lecture-audio/scripts/sync_knowledge.py            # export + show what changed, no git writes
    C:/Python313/python.exe workspace/lecture-audio/scripts/sync_knowledge.py --commit   # + pull --rebase, commit
    C:/Python313/python.exe workspace/lecture-audio/scripts/sync_knowledge.py --push     # + push (implies --commit)

The hub is a git repo on main; the executor runs only the default mode (no flags).
"""

import re
import subprocess
import sys
from datetime import date
from pathlib import Path

HUB = Path("D:/Proyectos/watch/grok-watch-hub")


def git(args, cwd):
    return subprocess.run(["git"] + args, cwd=str(cwd), capture_output=True, text=True)


def scrub(text):
    """Never print tokens or remote URLs that contain credentials."""
    return re.sub(r"(https?://)[^/\s@]+@", r"\1[redacted]@", text)


def stop(msg):
    print("STOP: " + msg)
    sys.exit(1)


def main():
    argv = sys.argv[1:]
    hub = HUB
    commit = push = False
    i = 0
    while i < len(argv):
        flag = argv[i]
        if flag == "--commit":
            commit = True
        elif flag == "--push":
            commit = push = True
        elif flag == "--hub":
            i += 1
            if i >= len(argv):
                stop("--hub needs a path")
            hub = Path(argv[i])
        else:
            stop(f"unknown flag {flag}")
        i += 1
    if not (hub / ".git").exists():
        stop(f"{hub} is not a git repository")
    branch = git(["rev-parse", "--abbrev-ref", "HEAD"], hub)
    if branch.returncode != 0 or branch.stdout.strip() != "main":
        stop(f"the hub is on '{branch.stdout.strip()}', not main")
    dirty = []
    for line in git(["status", "--porcelain"], hub).stdout.splitlines():
        if not line.strip():
            continue
        paths = [p.strip('"') for p in line[3:].split(" -> ")]
        if any(not p.startswith("knowledge/") for p in paths):
            dirty.append(line)
    if dirty:
        stop("the hub has local changes outside knowledge/:\n  " + "\n  ".join(dirty))
    if commit:
        pull = git(["pull", "--rebase", "--quiet", "origin", "main"], hub)
        if pull.returncode != 0:
            stop("git pull --rebase failed:\n" + scrub(pull.stderr))

    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import export_knowledge

    export_knowledge.main(hub / "knowledge" / "inn514")

    status = git(["status", "--short", "--", "knowledge/inn514"], hub).stdout.strip()
    if status:
        # The export stamps every file with today's date. When that stamp is the only
        # change, the pack content is unchanged: put the hub's checked-out files back.
        changed = [l for l in git(["diff", "--", "knowledge/inn514"], hub).stdout.splitlines()
                   if l[:1] in "+-" and not l.startswith(("+++", "---"))]
        if changed and all("Generated by workspace/lecture-audio/scripts/export_knowledge.py" in l for l in changed):
            git(["checkout", "--", "knowledge/inn514"], hub)
            status = git(["status", "--short", "--", "knowledge/inn514"], hub).stdout.strip()
    if not status:
        print("pack unchanged")
        return
    print(status)
    if not commit:
        return
    add = git(["add", "knowledge/inn514"], hub)
    if add.returncode != 0:
        stop("git add failed:\n" + scrub(add.stderr))
    message = f"knowledge: refresh the INN514 pack ({date.today().isoformat()})"
    committed = git(["commit", "-m", message], hub)
    if committed.returncode != 0:
        stop("git commit failed:\n" + scrub(committed.stdout + committed.stderr))
    print(message)
    if push:
        pushed = git(["push", "origin", "main"], hub)
        if pushed.returncode != 0:
            repull = git(["pull", "--rebase", "origin", "main"], hub)
            if repull.returncode != 0:
                stop("git pull --rebase failed:\n" + scrub(repull.stderr))
            pushed = git(["push", "origin", "main"], hub)
            if pushed.returncode != 0:
                stop("git push failed:\n" + scrub(pushed.stderr))
        print("pushed origin main")


if __name__ == "__main__":
    main()
